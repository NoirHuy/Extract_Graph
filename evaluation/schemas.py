"""Pydantic schemas and dataclasses for Multi-Agent Clinical Evaluation."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class TripletReviewItem(BaseModel):
    """Review feedback for a single clinical triplet row."""
    row_index: int
    source_name: str
    relation_type: str
    target_name: str
    status: str = Field(..., description="'PASS', 'WARNING', or 'FAIL'")
    agent_name: str = Field(..., description="Name of the reviewing agent")
    issue_type: Optional[str] = None
    critique: str = Field(..., description="Detailed clinical / technical critique")
    suggested_fix: Optional[Dict[str, Any]] = None


class AgentReviewReport(BaseModel):
    """Report generated by a single specialized reviewer agent."""
    agent_name: str
    total_reviewed: int
    pass_count: int
    warning_count: int
    fail_count: int
    reviews: List[TripletReviewItem] = Field(default_factory=list)


class EvaluationScorecard(BaseModel):
    """Overall quality scorecard produced by Chief Medical Adjudicator."""
    document_name: str
    total_triplets: int
    clinical_accuracy_score: float = Field(..., description="Score 0-100 from Clinical Agent")
    ontology_integrity_score: float = Field(..., description="Score 0-100 from UMLS Agent")
    graph_consistency_score: float = Field(..., description="Score 0-100 from Graph Inspector")
    overall_quality_score: float = Field(..., description="Weighted average 0-100")
    grade: str = Field(..., description="Letter grade e.g. A+, A, B, C")
    summary_findings: List[str] = Field(default_factory=list)
    agent_reports: Dict[str, AgentReviewReport] = Field(default_factory=dict)
    flagged_rows_count: int = 0
    auto_healed_rows_count: int = 0
